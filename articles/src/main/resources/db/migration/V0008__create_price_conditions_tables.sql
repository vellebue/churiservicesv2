CREATE SEQUENCE SEQ_PRICE_CONDITIONS START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_PRICE_CONDITION_SUBTYPES START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_PRICE_CONDITION_VALUES START WITH 1 INCREMENT BY 1;

CREATE TABLE C_PRICE_CONDITION_TYPES (
    condition_type VARCHAR(4) PRIMARY KEY,
    description VARCHAR(256) NOT NULL,
    condition_key VARCHAR(100) NOT NULL
);

CREATE TABLE C_PRICE_CONDITION_SUBTYPES (
    subtype_id BIGINT NOT NULL DEFAULT nextval('SEQ_PRICE_CONDITION_SUBTYPES') PRIMARY KEY,
    condition_type VARCHAR(4) NOT NULL REFERENCES C_PRICE_CONDITION_TYPES(condition_type),
    condition_subtype VARCHAR(4) NOT NULL,
    description VARCHAR(256) NOT NULL,
    subtype_key VARCHAR(100) NOT NULL,
    CONSTRAINT UK_PRICE_CONDITION_SUBTYPES_MNEMONIC UNIQUE (condition_type, condition_subtype)
);

CREATE TABLE PRICE_CONDITIONS (
    condition_id BIGINT NOT NULL DEFAULT nextval('SEQ_PRICE_CONDITIONS') PRIMARY KEY,
    subtype_id BIGINT NOT NULL REFERENCES C_PRICE_CONDITION_SUBTYPES(subtype_id),
    scope CHAR(1) NOT NULL,
    evaluation CHAR(1) NOT NULL
);

CREATE TABLE PRICE_CONDITION_VALUES (
    value_id BIGINT NOT NULL DEFAULT nextval('SEQ_PRICE_CONDITION_VALUES') PRIMARY KEY,
    condition_id BIGINT NOT NULL REFERENCES PRICE_CONDITIONS(condition_id) ON DELETE CASCADE,
    value_type CHAR(1) NOT NULL,
    value NUMERIC(12,6) NOT NULL,
    begin_date DATE NOT NULL,
    end_date DATE
);