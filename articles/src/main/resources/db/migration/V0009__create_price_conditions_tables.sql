CREATE SEQUENCE SEQ_PRICE_CONDITIONS START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_PRICE_CONDITION_VALUES START WITH 1 INCREMENT BY 1;

CREATE TABLE PRICE_CONDITIONS (
    condition_id BIGINT PRIMARY KEY,
    condition_type VARCHAR(4) NOT NULL REFERENCES C_PRICE_CONDITION_TYPES(condition_type),
    description VARCHAR(512) NOT NULL,
    scope CHAR(1) NOT NULL,
    evaluation CHAR(1) NOT NULL,
    availability CHAR(1) NOT NULL,
    num_order INTEGER NOT NULL
);

CREATE TABLE PRICE_CONDITION_VALUES (
    value_id BIGINT PRIMARY KEY,
    condition_id BIGINT NOT NULL REFERENCES PRICE_CONDITIONS(condition_id) ON DELETE CASCADE,
    type CHAR(1) NOT NULL,
    value NUMERIC(12, 6) NOT NULL,
    begin_date DATE NOT NULL,
    end_date DATE
);
